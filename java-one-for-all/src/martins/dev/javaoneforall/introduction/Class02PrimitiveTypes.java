package martins.dev.javaoneforall.introduction;

public class Class02PrimitiveTypes {
    public static void main(String[] args) {
        int age = 40;
        byte byteValue = 127;
        short shortValue = 127;
        int intValue = 127;
        long longValue = 127;
        float floatValue = 127.5F;
        double doubleValue = 127.2;
        char charValue = 77;
        boolean boolValue = true;
        System.out.println("The age of my mother is " + age);
        System.out.println(charValue);

        String name = "Dev.Martins";
        System.out.println("Hi, i am " + name);
    }
}
